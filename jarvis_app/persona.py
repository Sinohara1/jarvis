def assistant_name(settings: dict) -> str:
    return str(settings.get("assistant_name") or "").strip()[:30] or DEFAULT_NAME


def is_default_name(name: str) -> bool:
    return name.strip().lower() in ("джарвис", "jarvis")


def preset_key(settings: dict) -> str:
    k = str(settings.get("character_preset") or "")
    return k if k in PRESETS or k == CUSTOM else DEFAULT_PRESET


def character_text(settings: dict) -> str:
    txt = str(settings.get("character") or "").strip()
    if txt:
        return txt[:2000]
    k = preset_key(settings)
    return PRESETS[k]["prompt"] if k in PRESETS else PRESETS[DEFAULT_PRESET]["prompt"]


def nudge_text(settings: dict, level: int, task: str, left: str = "") -> str:
    lvl = max(1, min(3, int(level)))
    k = preset_key(settings)
    pool = PRESETS[k]["nudges"] if k in PRESETS else NEUTRAL_NUDGES
    user = str(settings.get("user_name") or "").strip()
    t = random.choice(pool[lvl])
    if not user:
        t = t.replace("{user}, ", "").replace("{user}", "")
        t = t[:1].upper() + t[1:]
    return t.format(task=task or "твоя задача", left=left or "немного", user=user)


def presets_payload() -> list[dict]:
    return [{"key": k, "label": v["label"], "prompt": v["prompt"], "voice": v["voice"], "rate": v["rate"]}
            for k, v in PRESETS.items()]
